"use client";

import { useEffect, useMemo, useState } from "react";
import { Stat } from "@/components/bits";
import { AccuracyCostChart, SweepCostChart, SweepQualityChart } from "@/components/charts";
import { ServerStatus } from "@/components/server-status";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { Tabs, TabsList, TabsTrigger } from "@/components/ui/tabs";
import { api } from "@/lib/api";
import { money, num, pct, secs } from "@/lib/format";
import type { EvalLatest } from "@/lib/types";
import { useBackend } from "@/lib/use-backend";

const ORDER = ["base", "tuned", "tuned_cpu", "tuned_cpu_norm", "teacher", "harness"];
const COLS: { key: string; label: string; fmt: (v: unknown) => string; hint?: string }[] = [
  { key: "intent_accuracy", label: "Intent", fmt: pct },
  { key: "json_validity_rate", label: "Valid JSON", fmt: pct },
  { key: "item_f1", label: "Item F1", fmt: pct, hint: "items matched by description AND quantity" },
  { key: "quantity_accuracy", label: "Qty acc.", fmt: pct },
  { key: "missing_info_f1", label: "Missing-info F1", fmt: pct },
  { key: "exact_match_rate", label: "Exact match", fmt: pct },
  { key: "sku_resolution_accuracy", label: "SKU resolution", fmt: pct, hint: "tools run on the extraction; top SKU correct" },
  { key: "latency_p50_s", label: "p50", fmt: secs },
  { key: "latency_p95_s", label: "p95", fmt: secs },
  { key: "escalation_rate", label: "Escalated", fmt: pct },
  { key: "cost_per_1k_usd", label: "Cost / 1k", fmt: (v) => (typeof v === "number" ? money(v, 3) : "–") },
];

export default function ResultsPage() {
  const backend = useBackend();
  const [data, setData] = useState<EvalLatest | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [split, setSplit] = useState("exam");

  useEffect(() => {
    if (backend.state === "ready") api.evalLatest().then(setData).catch((e) => setError(String(e)));
  }, [backend.state]);

  const systems = useMemo(
    () => ORDER.filter((k) => data?.systems?.[k]).map((k) => ({ key: k, ...data!.systems![k] })),
    [data],
  );
  const points = systems
    .filter((s) => s.key !== "tuned" && s.key !== "tuned_cpu_norm") // notebook cost isn't comparable; rule fixes don't change item F1 or cost
    .map((s) => ({ name: s.label.replace(/ \((CPU|student).*$/, "").replace(/^Fine-tuned Gemma 3 270M$/, "Small model (CPU)"), cost: Number(s.splits[split]?.cost_per_1k_usd ?? 0), f1: Number(s.splits[split]?.item_f1 ?? 0) }));

  return (
    <div className="mx-auto max-w-6xl space-y-6 px-4 py-8">
      <div>
        <h1 className="text-2xl font-semibold">Results</h1>
        <p className="text-sm text-muted-foreground">
          Base model vs fine-tuned small model vs large model vs the full harness, on a sealed exam. Every number on this page is
          read from the latest evaluation report file.
        </p>
      </div>
      <ServerStatus state={backend.state} elapsed={backend.elapsed} retry={backend.retry} />
      {error && <p className="text-sm text-destructive">{error}</p>}
      {data && !data.available && (
        <Card>
          <CardHeader>
            <CardTitle className="text-base">No evaluation report yet</CardTitle>
            <CardDescription>{data.message}</CardDescription>
          </CardHeader>
        </Card>
      )}
      {data?.available && (
        <>
          <div className="grid grid-cols-2 gap-3 md:grid-cols-4">
            <Stat label="Report" value={data.run ?? data.report_dir} hint={`generated ${data.created?.slice(0, 10) ?? ""}`} />
            <Stat
              label="Training examples"
              value={String((data.data?.splits as { train?: { n: number } } | null)?.train?.n ?? "–")}
              hint="synthetic, labels generated by code"
            />
            <Stat label="Verification drop rate" value={pct(data.data?.verification?.drop_rate)} hint="emails rejected by checks" />
            <Stat label="Router threshold" value={data.router_threshold != null ? num(data.router_threshold) : "–"} hint="chosen on the validation split" />
          </div>

          <Tabs value={split} onValueChange={setSplit}>
            <TabsList>
              <TabsTrigger value="exam">Exam (150)</TabsTrigger>
              <TabsTrigger value="exam_hard">Hard exam (30)</TabsTrigger>
            </TabsList>
          </Tabs>

          <Card>
            <CardHeader>
              <CardTitle className="text-base">Metrics · {split === "exam" ? "exam" : "hard exam"}</CardTitle>
              <CardDescription>Higher is better except latency and cost.</CardDescription>
            </CardHeader>
            <CardContent className="overflow-x-auto">
              <Table>
                <TableHeader>
                  <TableRow>
                    <TableHead className="min-w-52">System</TableHead>
                    {COLS.map((c) => (
                      <TableHead key={c.key} className="text-right whitespace-nowrap" title={c.hint}>
                        {c.label}
                      </TableHead>
                    ))}
                  </TableRow>
                </TableHeader>
                <TableBody>
                  {systems.map((s) => (
                    <TableRow key={s.key}>
                      <TableCell>
                        <p className="text-sm font-medium">{s.label}</p>
                        <p className="text-xs text-muted-foreground">{s.hardware ?? s.model}</p>
                      </TableCell>
                      {COLS.map((c) => (
                        <TableCell key={c.key} className="tabular text-right text-sm">
                          {c.fmt(s.splits[split]?.[c.key])}
                        </TableCell>
                      ))}
                    </TableRow>
                  ))}
                </TableBody>
              </Table>
            </CardContent>
          </Card>

          <div className="grid gap-4 lg:grid-cols-2">
            <Card>
              <CardHeader>
                <CardTitle className="text-base">Accuracy vs cost</CardTitle>
                <CardDescription>Item F1 on the {split === "exam" ? "exam" : "hard exam"} against cost per 1,000 emails.</CardDescription>
              </CardHeader>
              <CardContent>
                <AccuracyCostChart points={points} />
              </CardContent>
            </Card>
            {data.calibration ? (
              <Card>
                <CardHeader>
                  <CardTitle className="text-base">Router threshold sweep (validation split)</CardTitle>
                  <CardDescription>{data.calibration.rule}.</CardDescription>
                </CardHeader>
                <CardContent className="space-y-2">
                  <SweepQualityChart sweep={data.calibration.sweep} chosen={data.calibration.chosen.threshold} />
                  <SweepCostChart sweep={data.calibration.sweep} chosen={data.calibration.chosen.threshold} />
                </CardContent>
              </Card>
            ) : (
              <Card>
                <CardHeader>
                  <CardTitle className="text-base">Router threshold sweep</CardTitle>
                  <CardDescription>Not calibrated yet (needs student + teacher predictions on the validation split).</CardDescription>
                </CardHeader>
              </Card>
            )}
          </div>

          <Card>
            <CardHeader>
              <CardTitle className="text-base">How we measured</CardTitle>
            </CardHeader>
            <CardContent>
              <ul className="list-inside list-disc space-y-1 text-sm text-muted-foreground">
                {(data.how_measured ?? []).map((h) => (
                  <li key={h}>{h}</li>
                ))}
                {systems.map((s) =>
                  s.latency_note || s.cost_note ? (
                    <li key={s.key}>
                      <span className="text-foreground">{s.label}:</span> {[s.latency_note, s.cost_note].filter(Boolean).join("; ")}
                    </li>
                  ) : null,
                )}
              </ul>
            </CardContent>
          </Card>
        </>
      )}
    </div>
  );
}
